// Static anchor table for every film state: scripts/modelling/anchor-table.mjs -> src/eras/anchor-table.js.
// Each distinct film scene state (src/film/timeline.js, 1800 frames) is applied once on the CPU and every revealed
// feature gets an anchor from the five-eye picker (src/eras/anchor-picker.js). A feature keeps its previous anchor
// while that point is still a candidate seen from every eye, so a callout holds one point over its window. Features
// with an active callout must be seen from all five eyes; the script fails otherwise. The film and the CPU audit
// then read the same numbers, whatever the runtime.
// Usage: node scripts/modelling/anchor-table.mjs [--check]   (--check: compare with the committed table, write nothing)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createEraSite, anchorStateKey } from '../../src/eras/site-state.js';
import { filmState } from '../../src/film/timeline.js';
import { anchorSourceHash } from './anchor-sources.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const copy = JSON.parse(fs.readFileSync(path.join(root, 'reference', 'film-callouts.json'), 'utf8'));
const t0 = performance.now();
const states = new Map();
for (let frame = 0; frame < 1800; frame++) {
  const st = filmState(frame / 30), key = anchorStateKey(st.scene);
  let s = states.get(key);
  if (!s) states.set(key, s = { scene: st.scene, frames: [], required: new Set() });
  s.frames.push(frame);
  for (const c of st.overlays.callouts) if (c.opacity > 0) s.required.add(copy.sections[c.sectionIndex].callouts[c.slot].featureId);
}
const site = createEraSite({ anchorTable: null });
let features = null;
const points = [], pointIndex = new Map(), parts = [], table = {}, prefer = {}, failures = [], windows = {};
for (const [key, s] of states) {
  site.applyState(s.scene);
  const picked = site.pickFeatureAnchors(prefer);
  features ??= Object.keys(picked);
  table[key] = features.map(id => {
    const a = picked[id];
    if (!a.point) { delete prefer[id]; return -1; }
    if (s.required.has(id) && a.eyes !== 5) failures.push({ featureId: id, frames: `${s.frames[0]}-${s.frames.at(-1)}`, eyes: a.eyes });
    if (a.eyes === 5) prefer[id] = a.point.join(','); else delete prefer[id];
    const part = a.part === null ? -1 : (parts.includes(a.part) ? parts.indexOf(a.part) : parts.push(a.part) - 1);
    const p = [...a.point, ...a.normal, part], pk = p.join(',');
    if (!pointIndex.has(pk)) { pointIndex.set(pk, points.length); points.push(p); }
    if (s.required.has(id)) { (windows[id] ??= new Set()).add(pointIndex.get(pk)); }
    return pointIndex.get(pk) * 2 + (a.visible ? 1 : 0);
  });
}
const sourceHash = anchorSourceHash(root);
const report = { states: states.size, points: points.length, failures, calloutPoints: Object.fromEntries(Object.entries(windows).map(([id, s]) => [id, s.size])), seconds: +((performance.now() - t0) / 1000).toFixed(1), sourceHash };
console.log(JSON.stringify(report));
const body = `// Generated by scripts/modelling/anchor-table.mjs from the sources hashed below; do not edit. Regenerate after any
// change to the era stack, the feature kit, the seating, the cuts or the film timeline/camera.
// states: anchorStateKey(scene) -> per feature (order of \`features\`): -1 not revealed, else point index * 2 + visible.
// points: [x, y, z, nx, ny, nz, part index or -1], metres, rounded to 1e-6, already offset ${'1 cm'} along the normal.
export const ANCHOR_TABLE = ${JSON.stringify({ sourceHash, features, parts, points, states: table })};
`;
const file = path.join(root, 'src', 'eras', 'anchor-table.js');
if (process.argv.includes('--check')) {
  const same = fs.readFileSync(file, 'utf8') === body;
  console.log(same ? 'anchor table up to date' : 'anchor table differs from a fresh run');
  if (!same) process.exitCode = 1;
} else if (failures.length) { console.error('callout anchors not seen from every eye; table not written'); process.exitCode = 1; }
else fs.writeFileSync(file, body);
